"""Watermark + quote-cards finishing for studio videos.

Standing rules (user, 2026-11-21):
  * The «قصص وعبر» logo appears on EVERY Facebook video: a golden
    circular badge, top-right, 110px on a 720x1280 video, 20px margin.
    The badge is burned into the video file itself, so it also shows
    on YouTube (same file).
  * Every story gets 3 quote cards (عبرة / حكمة / موعظة دينية) in the
    page's golden style, 720x1280, generated by make_quote_cards.py,
    appended as 3-second silent closing slides. Main content therefore
    targets 31-51s so the TOTAL stays within the 40-60s rule.
  * Ready-made videos (already 40-60s) get the watermark only; the
    cards are generated and saved with the story, not appended.
"""
import os
import subprocess
import sys

STUDIO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BADGE_DEFAULT = os.path.join(STUDIO_DIR, "assets", "qisas-logo-badge.png")
MAKE_CARDS = os.path.join(STUDIO_DIR, "make_quote_cards.py")

LOGO_SIZE = 110
LOGO_MARGIN = 20
CARD_SECONDS = 3


class WatermarkError(Exception):
    pass


def _run(cmd, timeout=600):
    try:
        r = subprocess.run(cmd, capture_output=True, text=True,
                           timeout=timeout)
    except subprocess.TimeoutExpired:
        raise WatermarkError("انتهت المهلة أثناء تنفيذ ffmpeg: %s"
                             % " ".join(cmd[:4]))
    if r.returncode != 0:
        raise WatermarkError("فشل ffmpeg (%s): %s"
                             % (r.returncode, (r.stderr or "").strip()[-500:]))
    return r


def probe_duration(path):
    r = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=noprint_wrappers=1:nokey=1", path],
        capture_output=True, text=True, timeout=30)
    if r.returncode != 0:
        raise WatermarkError("تعذر قراءة مدة %s" % path)
    return float(r.stdout.strip())


def probe_size(path):
    r = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v:0",
         "-show_entries", "stream=width,height,r_frame_rate",
         "-of", "default=noprint_wrappers=1", path],
        capture_output=True, text=True, timeout=30)
    if r.returncode != 0:
        raise WatermarkError("تعذر قراءة أبعاد %s" % path)
    out = dict(line.split("=", 1) for line in r.stdout.strip().splitlines()
               if "=" in line)
    return int(out["width"]), int(out["height"])


def apply_watermark(video, out, badge=None, size=LOGO_SIZE,
                    margin=LOGO_MARGIN):
    """Overlay the page logo badge, top-right, on the whole video.

    Re-encodes video (libx264 crf 20), copies audio untouched.
    """
    badge = badge or BADGE_DEFAULT
    if not os.path.isfile(video):
        raise WatermarkError("ملف الفيديو غير موجود: %s" % video)
    if not os.path.isfile(badge):
        raise WatermarkError("ملف الشعار غير موجود: %s" % badge)
    tmp = out + ".wm-tmp.mp4"
    _run(["ffmpeg", "-y", "-v", "error", "-i", video, "-i", badge,
          "-filter_complex",
          "[1:v]scale=%d:%d[logo];[0:v][logo]overlay=W-w-%d:%d:format=yuv420"
          % (size, size, margin, margin),
          "-c:v", "libx264", "-crf", "20", "-c:a", "copy",
          "-movflags", "+faststart", tmp])
    os.replace(tmp, out)
    return out


def append_quote_cards(video, cards, out, card_seconds=CARD_SECONDS):
    """Append quote-card images as silent closing slides.

    Each card shows for `card_seconds` at the video's own size/fps.
    Audio of the main video is kept; cards are silent.
    """
    if not cards:
        raise WatermarkError("لا بطاقات لإلحاقها")
    if not os.path.isfile(video):
        raise WatermarkError("ملف الفيديو غير موجود: %s" % video)
    for c in cards:
        if not os.path.isfile(c):
            raise WatermarkError("ملف البطاقة غير موجود: %s" % c)
    w, h = probe_size(video)
    n = len(cards)
    cmd = ["ffmpeg", "-y", "-v", "error", "-i", video]
    for c in cards:
        cmd += ["-loop", "1", "-t", str(card_seconds), "-i", c]
    # صمت مستقل لكل بطاقة (asplit كان يعطي كل فرع الصمت كاملًا فيطيل
    # المقطع) — مدخل anullsrc منفصل 3 ثوانٍ لكل بطاقة.
    for _ in cards:
        cmd += ["-f", "lavfi", "-t", str(card_seconds),
                "-i", "anullsrc=r=48000:cl=stereo"]
    filt = ["[0:v]scale=%d:%d,fps=30,setsar=1[v0]" % (w, h),
            "[0:a]aresample=48000,aformat=channel_layouts=stereo[a0]"]
    for i in range(n):
        filt.append("[%d:v]scale=%d:%d,fps=30,setsar=1[v%d]"
                    % (i + 1, w, h, i + 1))
    concat_inputs = "[v0][a0]"
    for i in range(n):
        concat_inputs += "[v%d][%d:a]" % (i + 1, n + 1 + i)
    filt.append("%sconcat=n=%d:v=1:a=1[v][a]" % (concat_inputs, n + 1))
    cmd += ["-filter_complex", ";".join(filt),
            "-map", "[v]", "-map", "[a]",
            "-c:v", "libx264", "-crf", "20", "-c:a", "aac",
            "-movflags", "+faststart", out]
    _run(cmd)
    return out


def generate_quote_cards(ibra, hikma, mawiza, mawiza_source, out_dir):
    """Generate the 3 quote cards via make_quote_cards.py.

    Returns [ibra_path, hikma_path, mawiza_path] in that order.
    """
    if not os.path.isfile(MAKE_CARDS):
        raise WatermarkError("سكربت البطاقات غير موجود: %s" % MAKE_CARDS)
    # ملاحظة (اختبار اختراق 2026-11-21): out_dir مسار حر يختاره
    # المشغّل (CLI أو كرون بمجلد ثابت) لا مدخل من ملف بيانات،
    # فلا يُحصَر — الكتابة هنا مقصودة by design.
    os.makedirs(out_dir, exist_ok=True)
    jobs = [("عبرة", ibra, "ibra.png", ""),
            ("حكمة", hikma, "hikma.png", ""),
            ("موعظة", mawiza, "mawiza.png", mawiza_source or "")]
    paths = []
    for kind, text, name, source in jobs:
        out = os.path.join(out_dir, name)
        cmd = [sys.executable, MAKE_CARDS, "--kind", kind,
               "--text", text, "--out", out]
        if source:
            cmd += ["--source", source]
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
        if r.returncode != 0:
            raise WatermarkError("فشل توليد بطاقة %s: %s"
                                 % (kind, (r.stderr or "").strip()[-300:]))
        paths.append(out)
    return paths


def find_cards(cards_dir):
    """Return [ibra, hikma, mawiza] paths from a cards directory."""
    cands = {}
    for name in os.listdir(cards_dir):
        low = name.lower()
        if not low.endswith(".png"):
            continue
        if "ibra" in low or "عبرة" in low or "ibra" in low:
            cands["ibra"] = os.path.join(cards_dir, name)
        elif "hikma" in low or "حكمة" in low:
            cands["hikma"] = os.path.join(cards_dir, name)
        elif "mawiza" in low or "موعظة" in low:
            cands["mawiza"] = os.path.join(cards_dir, name)
    missing = [k for k in ("ibra", "hikma", "mawiza") if k not in cands]
    if missing:
        raise WatermarkError("مجلد البطاقات %s ينقصه: %s"
                             % (cards_dir, ", ".join(missing)))
    return [cands["ibra"], cands["hikma"], cands["mawiza"]]
